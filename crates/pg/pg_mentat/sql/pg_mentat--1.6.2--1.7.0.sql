-- pg_mentat 1.6.2 -> 1.7.0 upgrade.
--
-- 1.7.0 is the first release of the merged repository (the embedded `mentat`
-- SQLite store and this PostgreSQL extension now live together at
-- codeberg.org/gregburd/mentat and share one front-end). For the extension,
-- the changes relative to 1.6.2 are all in the compiled module (Rust) — there
-- is no change to the default-build SQL objects, schema, or catalog:
--
-- * The optional mino scripting surface `mentat_eval(TEXT)` (behind the
--   `script` cargo feature; NOT in default builds) now runs a sandboxed
--   interpreter with no host-filesystem access and enforces three
--   superuser-only limit GUCs — `mentat.script_max_steps`,
--   `mentat.script_max_heap_bytes`, `mentat.script_max_depth` — plus
--   `statement_timeout`. When the `script` feature is compiled in, that
--   function's SQL definition is generated by the module; this migration
--   does not create it (a non-script build has no such function).
-- * The shared front-end grammar gained 5-place history patterns, `:in`
--   source vars, and plain-keyword pattern values; the SQLite transactor
--   gained `:db.fn/cas`/`:db/retractEntity`. These do not affect the
--   extension's SQL surface.
--
-- This migration intentionally does nothing to the catalog; it exists so that
-- `ALTER EXTENSION pg_mentat UPDATE TO '1.7.0'` succeeds and the recompiled
-- module is picked up.
